import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { config } from '../platform/config';
import { provisionRoles, withCredentials, API_LOGIN_ROLE, WORKER_LOGIN_ROLE } from './provision';

/**
 * Create/refresh the restricted LOGIN roles used by the API and the worker.
 *
 *   npm run db:provision                      passwords from DB_API_PASSWORD / DB_WORKER_PASSWORD (required in production)
 *   npm run db:provision -- --write-env       development: generate strong passwords if absent and append the resulting
 *                                             connection strings to .env.native (gitignored). Nothing secret is printed.
 *
 * Uses MIGRATOR_DATABASE_URL (a privileged role). Safe to run repeatedly.
 */
async function main() {
  const writeEnv = process.argv.includes('--write-env');
  if (config.isProduction && writeEnv) throw new Error('--write-env is for local development only');

  const gen = () => crypto.randomBytes(24).toString('hex');
  const apiPassword = process.env.DB_API_PASSWORD ?? (writeEnv ? gen() : undefined);
  const workerPassword = process.env.DB_WORKER_PASSWORD ?? (writeEnv ? gen() : undefined);
  if (!apiPassword || !workerPassword) throw new Error('Set DB_API_PASSWORD and DB_WORKER_PASSWORD (or use --write-env in development)');

  await provisionRoles({ adminConnectionString: config.migratorDatabaseUrl, apiPassword, workerPassword });
  console.log(`[provision] roles ready: ${API_LOGIN_ROLE}, ${WORKER_LOGIN_ROLE}`);

  if (writeEnv) {
    const file = path.resolve(process.cwd(), '.env.native');
    const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (/^RESTRICTED_DATABASE_URL=/m.test(existing)) {
      console.log('[provision] .env.native already has RESTRICTED_* entries; passwords were NOT rotated in the file.');
      console.log('            To rotate: remove those two lines and run again.');
      // Roles were just re-passworded above to a NEW random value; keep the file consistent by re-applying the file's values.
      const m = (k: string) => new RegExp(`^${k}=(.*)$`, 'm').exec(existing)?.[1];
      const api = m('RESTRICTED_DATABASE_URL');
      const wrk = m('RESTRICTED_WORKER_DATABASE_URL');
      if (api && wrk) {
        const pw = (u: string) => decodeURIComponent(new URL(u).password);
        await provisionRoles({ adminConnectionString: config.migratorDatabaseUrl, apiPassword: pw(api), workerPassword: pw(wrk) });
      }
      return;
    }
    const lines = [
      '',
      '# --- Restricted runtime roles (generated by `npm run db:provision -- --write-env`). RLS is ENFORCED with these. ---',
      '# To run the API/worker under them, copy into DATABASE_URL / WORKER_DATABASE_URL (after legacy routes are removed).',
      `RESTRICTED_DATABASE_URL=${withCredentials(config.migratorDatabaseUrl, API_LOGIN_ROLE, apiPassword)}`,
      `RESTRICTED_WORKER_DATABASE_URL=${withCredentials(config.migratorDatabaseUrl, WORKER_LOGIN_ROLE, workerPassword)}`,
      '',
    ];
    fs.appendFileSync(file, lines.join('\n'));
    console.log('[provision] appended RESTRICTED_DATABASE_URL and RESTRICTED_WORKER_DATABASE_URL to .env.native');
  }
}

main().catch((e) => {
  console.error('[provision] failed:', e.message);
  process.exit(1);
});
